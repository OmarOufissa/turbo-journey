export async function removeDemoEmployees(): Promise<void> {
  try {
    const all = await db.select({ id: schema.employees.id, matricule: schema.employees.matricule })
      .from(schema.employees);

    const toDelete = all.filter(e => !VALID_MATRICULES.has(e.matricule));
    if (toDelete.length === 0) return;

    const ids = toDelete.map(e => e.id);
    await db.delete(schema.employees).where(inArray(schema.employees.id, ids));
    logger.warn("app", `Removed ${toDelete.length} non-Excel employees: ${toDelete.map(e => e.matricule).join(", ")}`);
  } catch (err) {
    logger.error("app", "Failed to remove demo employees", { error: String(err) });
  }
}
